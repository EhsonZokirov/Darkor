-- ---------- 5. Права доступа (Row Level Security) ----------

alter table public.profiles         enable row level security;
alter table public.bloggers         enable row level security;
alter table public.blogger_contacts enable row level security;
alter table public.ad_requests      enable row level security;
alter table public.messages         enable row level security;

-- profiles: каждый видит только свой профиль, админ — все. Менять роль нельзя никому
-- (администратора назначают вручную в SQL Editor, см. конец файла).
drop policy if exists "profiles: read own or admin" on public.profiles;
create policy "profiles: read own or admin" on public.profiles
  for select using (id = auth.uid() or public.is_admin());

-- bloggers: всем видны только одобренные; владелец видит свою анкету, админ — все.
drop policy if exists "bloggers: read" on public.bloggers;
create policy "bloggers: read" on public.bloggers
  for select using (status = 'approved' or user_id = auth.uid() or public.is_admin());

drop policy if exists "bloggers: insert" on public.bloggers;
create policy "bloggers: insert" on public.bloggers
  for insert to authenticated
  with check (user_id = auth.uid() or public.is_admin());

drop policy if exists "bloggers: update" on public.bloggers;
create policy "bloggers: update" on public.bloggers
  for update to authenticated
  using (user_id = auth.uid() or public.is_admin())
  with check (user_id = auth.uid() or public.is_admin());

drop policy if exists "bloggers: delete" on public.bloggers;
create policy "bloggers: delete" on public.bloggers
  for delete to authenticated
  using (user_id = auth.uid() or public.is_admin());

-- blogger_contacts: только владелец анкеты и админ.
drop policy if exists "contacts: owner or admin" on public.blogger_contacts;
create policy "contacts: owner or admin" on public.blogger_contacts
  for all to authenticated
  using (
    public.is_admin()
    or exists (select 1 from public.bloggers b where b.id = blogger_id and b.user_id = auth.uid())
  )
  with check (
    public.is_admin()
    or exists (select 1 from public.bloggers b where b.id = blogger_id and b.user_id = auth.uid())
  );

-- ad_requests и messages: отправить может любой посетитель, читать и удалять — только админ.
drop policy if exists "ad_requests: anyone can send" on public.ad_requests;
create policy "ad_requests: anyone can send" on public.ad_requests
  for insert to anon, authenticated with check (not is_read);

drop policy if exists "ad_requests: admin reads" on public.ad_requests;
create policy "ad_requests: admin reads" on public.ad_requests
  for select to authenticated using (public.is_admin());

drop policy if exists "ad_requests: admin updates" on public.ad_requests;
create policy "ad_requests: admin updates" on public.ad_requests
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "ad_requests: admin deletes" on public.ad_requests;
create policy "ad_requests: admin deletes" on public.ad_requests
  for delete to authenticated using (public.is_admin());

drop policy if exists "messages: anyone can send" on public.messages;
create policy "messages: anyone can send" on public.messages
  for insert to anon, authenticated with check (not is_read);

drop policy if exists "messages: admin reads" on public.messages;
create policy "messages: admin reads" on public.messages
  for select to authenticated using (public.is_admin());

drop policy if exists "messages: admin updates" on public.messages;
create policy "messages: admin updates" on public.messages
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "messages: admin deletes" on public.messages;
create policy "messages: admin deletes" on public.messages
  for delete to authenticated using (public.is_admin());


-- ---------- 6. Хранилище фото (бакет avatars) ----------
-- Читать может кто угодно, загружать — только вошедший пользователь в свою папку.
-- Размер до 3 МБ, форматы JPG/PNG/WebP.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('avatars', 'avatars', true, 3145728, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "avatars: public read" on storage.objects;
create policy "avatars: public read" on storage.objects
  for select using (bucket_id = 'avatars');

drop policy if exists "avatars: upload to own folder" on storage.objects;
create policy "avatars: upload to own folder" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "avatars: update own" on storage.objects;
create policy "avatars: update own" on storage.objects
  for update to authenticated
  using (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "avatars: delete own" on storage.objects;
create policy "avatars: delete own" on storage.objects
  for delete to authenticated
  using (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text);


-- ---------- 7. Защита от потока заявок ----------
-- Если за последние 10 минут пришло 30 и больше заявок (или сообщений),
-- новые временно отклоняются. Это защищает админку от бота-спамера.
-- Лимит можно изменить: число 30 ниже.

create or replace function public.limit_submissions()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  recent integer;
begin
  execute format(
    'select count(*) from public.%I where created_at > now() - interval ''10 minutes''',
    tg_table_name
  ) into recent;

  if recent >= 30 then
    raise exception 'Слишком много заявок, попробуйте позже' using errcode = 'P0001';
  end if;

  return new;
end;
$$;

drop trigger if exists ad_requests_limit_trg on public.ad_requests;
create trigger ad_requests_limit_trg
  before insert on public.ad_requests
  for each row execute function public.limit_submissions();

drop trigger if exists messages_limit_trg on public.messages;
create trigger messages_limit_trg
  before insert on public.messages
  for each row execute function public.limit_submissions();


-- ---------- 8. SMM-специалисты ----------
-- Карточки SMM-специалистов для раздела «SMM». Добавляет и правит только администратор
-- (в админ-панели). Контакты здесь публичные: специалисты хотят получать заказы.

create table if not exists public.smm_specialists (
  id          bigint generated always as identity primary key,
  name        text not null check (char_length(name) between 2 and 80),
  city        text not null default 'Душанбе' check (char_length(city) between 2 and 60),
  specialty   text not null check (char_length(specialty) between 2 and 120),
  services    text[] not null default '{}',
  price       integer not null default 0 check (price >= 0),
  instagram   text not null default '' check (char_length(instagram) <= 200),
  telegram    text not null default '' check (char_length(telegram) <= 200),
  contact     text not null default '' check (char_length(contact) <= 200),
  description text not null check (char_length(description) between 10 and 2000),
  image_url   text,
  published   boolean not null default true,
  created_at  timestamptz not null default now()
);

alter table public.smm_specialists enable row level security;

drop policy if exists "smm: read" on public.smm_specialists;
create policy "smm: read" on public.smm_specialists
  for select using (published or public.is_admin());

drop policy if exists "smm: admin insert" on public.smm_specialists;
create policy "smm: admin insert" on public.smm_specialists
  for insert with check (public.is_admin());

drop policy if exists "smm: admin update" on public.smm_specialists;
create policy "smm: admin update" on public.smm_specialists
  for update using (public.is_admin()) with check (public.is_admin());

drop policy if exists "smm: admin delete" on public.smm_specialists;
create policy "smm: admin delete" on public.smm_specialists
  for delete using (public.is_admin());

