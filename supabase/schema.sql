-- ---------- 1. Профили пользователей (роль: blogger / admin) ----------

create table if not exists public.profiles (
  id         uuid primary key references auth.users (id) on delete cascade,
  role       text not null default 'blogger' check (role in ('blogger', 'admin')),
  created_at timestamptz not null default now()
);

-- При регистрации автоматически создаём профиль с ролью blogger.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id) values (new.id) on conflict do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Является ли текущий пользователь администратором.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;


-- ---------- 2. Блогеры ----------
-- id начинается с 1000, чтобы не пересекаться с блогерами из файла bloggers.js (1–10).

create table if not exists public.bloggers (
  id          bigint generated by default as identity (start with 1000) primary key,
  user_id     uuid unique references auth.users (id) on delete set null,
  name        text not null check (char_length(name) between 2 and 80),
  city        text not null check (char_length(city) between 2 and 80),
  gender      text not null check (gender in ('Мужчина', 'Женщина')),
  category    text not null check (char_length(category) between 2 and 40),
  instagram   text check (char_length(instagram) <= 200),
  tiktok      text check (char_length(tiktok) <= 200),
  youtube     text check (char_length(youtube) <= 200),
  price       integer not null default 0 check (price >= 0),
  description text not null check (char_length(description) between 10 and 2000),
  image_url   text check (char_length(image_url) <= 500),
  views       text,
  likes       text,
  engagement  text,
  tags        text[] not null default '{}',
  formats     text[] not null default '{}',
  status      text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists bloggers_status_idx on public.bloggers (status);

-- Защита модерации: обычный пользователь не может сам себя одобрить
-- и не может передать анкету другому пользователю.
-- Любая правка анкеты владельцем возвращает её на проверку.
-- (auth.uid() = null — это запрос из SQL Editor/сервера, там ограничений нет.)
create or replace function public.bloggers_guard()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is not null and not public.is_admin() then
    new.status := 'pending';
    if tg_op = 'UPDATE' then
      new.user_id := old.user_id;
    end if;
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists bloggers_guard_trg on public.bloggers;
create trigger bloggers_guard_trg
  before insert or update on public.bloggers
  for each row execute function public.bloggers_guard();


