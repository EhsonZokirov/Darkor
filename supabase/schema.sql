drop policy if exists "bloggers: read" on public.bloggers;
create policy "bloggers: read" on public.bloggers
  for select using (status = 'approved' or user_id = auth.uid() or public.is_admin());

drop policy if exists "bloggers: insert" on public.bloggers;
create policy "bloggers: insert" on public.bloggers
  for insert to authenticated
  with check (user_id = auth.uid() or public.is_admin());

drop policy if exists "bloggers: update" on public.bloggers;
create policy "bloggers: update" on public.bloggers
  for update to authenticated
  using (user_id = auth.uid() or public.is_admin())
  with check (user_id = auth.uid() or public.is_admin());

drop policy if exists "bloggers: delete" on public.bloggers;
create policy "bloggers: delete" on public.bloggers
  for delete to authenticated
  using (user_id = auth.uid() or public.is_admin());

-- blogger_contacts: только владелец анкеты и админ.
drop policy if exists "contacts: owner or admin" on public.blogger_contacts;
create policy "contacts: owner or admin" on public.blogger_contacts
  for all to authenticated
  using (
    public.is_admin()
    or exists (select 1 from public.bloggers b where b.id = blogger_id and b.user_id = auth.uid())
  )
  with check (
    public.is_admin()
    or exists (select 1 from public.bloggers b where b.id = blogger_id and b.user_id = auth.uid())
  );

